"""Privilege rehearsal only against an explicitly supplied disposable database."""

import os
from pathlib import Path

import asyncpg
import pytest
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.ext.asyncio import create_async_engine

URL = os.environ.get("TEST_RUNTIME_ROLE_DB_URL")
pytestmark = pytest.mark.skipif(not URL, reason="requires disposable PostgreSQL database")


@pytest.mark.asyncio
async def test_runtime_role_cannot_mutate_audit_or_schema_version():
    engine = create_async_engine(URL)
    sql = (Path(__file__).parents[2] / "scripts/prepare-runtime-db-role.sql").read_text()
    sql = sql.replace("\\set ON_ERROR_STOP on", "")
    drop_sql = (
        (Path(__file__).parents[2] / "scripts/rehearse-tenant-schema-drop.sql")
        .read_text()
        .replace("\\set ON_ERROR_STOP on", "")
    )
    refresh_sql = (
        (Path(__file__).parents[2] / "scripts/rehearse-refresh-runtime-grants.sql")
        .read_text()
        .replace("\\set ON_ERROR_STOP on", "")
    )
    sql = sql.replace("\\ir rehearse-refresh-runtime-grants.sql", refresh_sql)
    async with engine.begin() as conn:
        await conn.execute(
            text(
                "CREATE TABLE public.audit_logs (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_slug text, user_type text, action text, resource_type text, resource_id text, details jsonb)"
            )
        )
        await conn.execute(
            text("CREATE TABLE public.alembic_version (version_num text PRIMARY KEY)")
        )
        await conn.execute(text("CREATE TABLE public.admins (id integer PRIMARY KEY)"))
        await conn.execute(
            text("CREATE TABLE public.tenants (id uuid PRIMARY KEY, slug text, status text)")
        )
        await conn.execute(
            text("INSERT INTO public.tenants VALUES (gen_random_uuid(),'existing','active')")
        )
        await conn.execute(text("CREATE SCHEMA tenant_template"))
        await conn.execute(text("CREATE TABLE tenant_template.contacts (id integer PRIMARY KEY)"))
        await conn.execute(text("CREATE SCHEMA tenant_existing"))
        await conn.execute(text("CREATE TABLE tenant_existing.contacts (id integer PRIMARY KEY)"))
    async with engine.connect() as conn:
        raw = await conn.get_raw_connection()
        await raw.driver_connection.execute(sql)
        await raw.driver_connection.execute(drop_sql)
        await conn.execute(text("SET ROLE cri_runtime_access"))
        await conn.execute(text("INSERT INTO public.audit_logs (action) VALUES ('test')"))
        await conn.execute(text("INSERT INTO tenant_existing.contacts VALUES (1)"))
        await conn.execute(text("CREATE SCHEMA tenant_new"))
        await conn.execute(
            text("CREATE TABLE tenant_new.contacts (LIKE tenant_template.contacts INCLUDING ALL)")
        )
        await conn.execute(
            text("CREATE TABLE tenant_new.links (admin_id integer REFERENCES public.admins(id))")
        )
        await conn.commit()
        for statement in [
            "UPDATE public.audit_logs SET action='modified'",
            "DELETE FROM public.audit_logs",
            "TRUNCATE public.audit_logs",
            "INSERT INTO public.alembic_version VALUES ('forged')",
            "DROP SCHEMA tenant_existing CASCADE",
        ]:
            with pytest.raises(DBAPIError):
                await conn.execute(text(statement))
            await conn.rollback()
        # Migration-created tables do not inherit broad default privileges.
        await conn.execute(text("RESET ROLE"))
        await conn.execute(text("CREATE TABLE public.dossier_import_requests (id integer GENERATED BY DEFAULT AS IDENTITY)"))
        await conn.execute(text("CREATE TABLE tenant_template.kb_documents (id integer)"))
        await conn.commit()
        await conn.execute(text("SET ROLE cri_runtime_access"))
        await conn.commit()
        for statement in [
            "SELECT * FROM public.dossier_import_requests",
            "SELECT * FROM tenant_template.kb_documents",
        ]:
            with pytest.raises(DBAPIError):
                await conn.execute(text(statement))
            await conn.rollback()
        await conn.execute(text("RESET ROLE"))
        await conn.commit()
        await conn.execute(text("CREATE TABLE public.unreviewed_table (id integer)"))
        await conn.commit()
        raw = await conn.get_raw_connection()
        with pytest.raises(asyncpg.PostgresError, match="Unknown table"):
            await raw.driver_connection.execute(refresh_sql)
        await conn.rollback()
        await conn.execute(text("DROP TABLE public.unreviewed_table"))
        await conn.commit()
        await conn.execute(text("CREATE SEQUENCE public.unreviewed_sequence"))
        await conn.commit()
        with pytest.raises(asyncpg.PostgresError, match="Unknown sequence"):
            await raw.driver_connection.execute(refresh_sql)
        await conn.rollback()
        await conn.execute(text("DROP SEQUENCE public.unreviewed_sequence"))
        await conn.commit()
        await raw.driver_connection.execute(refresh_sql)
        await conn.execute(text("SET ROLE cri_runtime_access"))
        await conn.commit()
        await conn.execute(text("INSERT INTO public.dossier_import_requests DEFAULT VALUES"))
        await conn.execute(text("INSERT INTO tenant_template.kb_documents VALUES (1)"))
        await conn.commit()
        with pytest.raises(DBAPIError):
            await conn.execute(text("UPDATE public.audit_logs SET action='modified'"))
        await conn.rollback()
        await conn.execute(text("DROP SCHEMA tenant_new CASCADE"))
        await conn.commit()
        for slug in ["existing", "template", "existing; DROP SCHEMA public", "missing"]:
            with pytest.raises(DBAPIError):
                await conn.execute(
                    text("SELECT public.rehearsal_drop_tenant_schema(:slug)"), {"slug": slug}
                )
            await conn.rollback()
        await conn.execute(text("RESET ROLE"))
        await conn.execute(
            text("UPDATE public.tenants SET status='inactive' WHERE slug='existing'")
        )
        await conn.execute(
            text(
                "ALTER TABLE public.audit_logs ADD CONSTRAINT reject_schema_drop CHECK (action <> 'tenant_schema_drop') NOT VALID"
            )
        )
        await conn.commit()
        await conn.execute(text("SET ROLE cri_runtime_access"))
        with pytest.raises(DBAPIError):
            await conn.execute(text("SELECT public.rehearsal_drop_tenant_schema('existing')"))
        await conn.rollback()
        assert (
            await conn.execute(text("SELECT to_regnamespace('tenant_existing') IS NOT NULL"))
        ).scalar_one()
        await conn.execute(text("RESET ROLE"))
        await conn.execute(text("ALTER TABLE public.audit_logs DROP CONSTRAINT reject_schema_drop"))
        await conn.commit()
        await conn.execute(text("SET ROLE cri_runtime_access"))
        await conn.execute(text("SELECT public.rehearsal_drop_tenant_schema('existing')"))
        await conn.commit()
        assert (
            await conn.execute(text("SELECT to_regnamespace('tenant_existing') IS NULL"))
        ).scalar_one()
        assert (
            await conn.execute(
                text("SELECT count(*) FROM public.audit_logs WHERE action='tenant_schema_drop'")
            )
        ).scalar_one() == 1
        assert (
            await conn.execute(text("SELECT action FROM public.audit_logs WHERE id=1"))
        ).scalar_one() == "test"
        await conn.execute(text("RESET ROLE"))
        await conn.execute(text("DROP OWNED BY cri_runtime_access"))
        await conn.execute(text("DROP ROLE cri_runtime_access"))
        await conn.commit()
    await engine.dispose()
